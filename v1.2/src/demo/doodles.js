let cache = null;

export function renderDemoAsset(slotId) {
  const slot = SLOT_BY_ID[slotId];
  const entry = DEMO[slotId];
  if (!slot || !entry) return null;
  const bitmap = renderOps(entry.ops, slot.width, slot.height);
  const rig = entry.rig
    ? { behaviour: entry.rig.behaviour, points: Object.assign({}, entry.rig.points) }
    : { behaviour: slot.defaultBehaviour, points: {} };
  return { slotId, width: slot.width, height: slot.height, bitmap, rig, tempo: slot.tempo };
}

export function renderAllDemoAssets() {
  if (cache) return cache;
  const map = new Map();
  Object.keys(DEMO).forEach((slotId) => {
    const asset = renderDemoAsset(slotId);
    if (asset) map.set(slotId, asset);
  });
  cache = map;
  return map;
}
